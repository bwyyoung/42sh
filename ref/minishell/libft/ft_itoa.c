#include "libft.h"

char	*ft_itoa(int n)
{
	static char		buf[21];
	char			*p;

	p = buf + 20;
	if (n >= 0)
	{
		*--p = '0' + (n % 10);
		while ((n /= 10) != 0)
			*--p = '0' + (n % 10);
	}
	else
	{
		*--p = '0' - (n % 10);
		while ((n /= 10) != 0)
			*--p = '0' - (n % 10);
		*--p = '-';
	}
	return (p);
}
