#include "libft.h"

void		*ft_memchr(const void *str, int c, size_t n)
{
	const char		*p_str;
	size_t			i;

	p_str = (const char *)str;
	i = 0;
	while (i < n)
	{
		if (p_str[i] == c)
			return ((char *)(str + i));
		i++;
	}
	return (NULL);
}
