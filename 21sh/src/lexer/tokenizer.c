#include "../../includes/ft_sh.h"

int			tokenize(t_shell **shell)
{
	if (get_tokens(shell) == 1)
		return (1);
	reorganize_tokens(shell);
	scan_heredocs(shell);
	(*shell)->tree = build_tree((*shell)->tkns);
	(*shell)->tkns = NULL;
	return (0);
}
