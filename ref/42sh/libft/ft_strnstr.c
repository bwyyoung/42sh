#include "libft.h"

char	*ft_strnstr(const char *s1, const char *s2, size_t n)
{
	size_t		i;
	size_t		j;

	if (!s1)
		return (NULL);
	if (!(*s2))
		return ((char *)s1);
	i = 0;
	while (s1[i] && i < n)
	{
		j = 0;
		while (s1[i + j] == s2[j] && i + j < n)
		{
			j++;
			if (!s2[j])
				return ((char *)(&s1[i]));
		}
		i++;
	}
	return (NULL);
}
